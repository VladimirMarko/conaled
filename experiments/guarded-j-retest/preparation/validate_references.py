"""Check exact private inputs through an integrated, audit-recognized module."""
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import json
import re
import subprocess
import sys
import time

repo = Path(__file__).resolve().parents[3]
prep = Path(__file__).resolve().parent
module_name = 'Examples.GuardedJRetestValidation'
module = repo / 'Examples/GuardedJRetestValidation.lean'
inputs = [prep / p for p in ['BaselineReference.lean', 'CandidateReference.lean', 'NativeCases.lean']]
imports, bodies = [], []
body_hashes = {}
for source in inputs:
    lines = source.read_text().splitlines()
    imports.extend(line for line in lines if line.startswith('import '))
    body = '\n'.join(line for line in lines if not line.startswith('import '))
    bodies.append(body)
    body_hashes[str(source.relative_to(repo))] = sha256(body.encode()).hexdigest()
header = '''/-! Generated private reference and native-case validation for #323.
The exact inputs are under experiments/guarded-j-retest/preparation/.
validate_references.py hoists their imports and checks the remaining bodies
byte-for-byte after joining lines with LF. This module is integrated for the
normal exhaustive audit and excluded from both frozen author handoffs.
Scope and evidence: experiments/guarded-j-retest/README.md. -/'''
expected = '\n'.join(dict.fromkeys(imports)) + '\n\n' + header + '\n' + '\n'.join(bodies) + '\n'
if sys.argv[1:] == ['--generate']:
    module.write_text(expected)
    print(module_name)
    raise SystemExit(0)
assert module.read_bytes() == expected.encode(), 'Integrated validation module differs from exact private inputs; regenerate before checking'
assert f'import {module_name}' in (repo / 'SquareApplications.lean').read_text().splitlines()
name = sys.argv[1]
audit = '--audit' in sys.argv[2:]
dest = prep / 'checks' / name
dest.mkdir(parents=True, exist_ok=False)
record = {'start': datetime.now(timezone.utc).isoformat(), 'audit': audit, 'module': module_name,
          'inputs': {}, 'input_body_sha256': body_hashes,
          'transformation': 'Hoist unique import lines in first-appearance order; join each remaining input body with LF; concatenate bodies in BaselineReference, CandidateReference, NativeCases order after the fixed generated-module comment. Exact generated bytes checked before invocation.'}
for source in inputs + [module, repo / 'SquareApplications.lean', repo / 'ProofAudit.lean']:
    content = source.read_bytes()
    (dest / (source.name + '.txt')).write_bytes(content)
    record['inputs'][str(source.relative_to(repo))] = sha256(content).hexdigest()
command = ['./check.sh'] if audit else ['lake', 'build', module_name]
record['command'] = command
started = time.monotonic()
with (dest / 'stdout.log').open('wb') as stdout, (dest / 'stderr.log').open('wb') as stderr:
    result = subprocess.run(command, cwd=repo, stdout=stdout, stderr=stderr)
record.update(command_exit=result.returncode, elapsed_seconds=time.monotonic() - started,
              finish=datetime.now(timezone.utc).isoformat())
exit_code = result.returncode
if audit:
    matches = re.findall(r'  Examples\.GuardedJRetestValidation: (\d+) logical declarations; (\d+) theorem declarations; (\d+) unsafe runtime declarations',
                         (dest / 'stdout.log').read_text())
    covered = len(matches) == 1 and int(matches[0][0]) > 0
    record['audit_scope_verified'] = covered
    if covered:
        record['audited_module_counts'] = dict(zip(['logical', 'theorem', 'unsafe_runtime'], map(int, matches[0])))
    elif exit_code == 0:
        exit_code = 2
        record['error'] = 'Command passed without a nonzero audited validation-module declaration count'
record['exit'] = exit_code
record['evidence_sha256'] = {p.name: sha256(p.read_bytes()).hexdigest() for p in sorted(dest.iterdir())}
(dest / 'result.json').write_text(json.dumps(record, indent=2) + '\n')
print(json.dumps({'archive': str(dest), 'exit': exit_code, 'audit': audit,
                  'audited_module_counts': record.get('audited_module_counts')}))
raise SystemExit(exit_code)
